export function resolveInitialDemoDate(): string {
  const now = new Date();
  const iso = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(
    now.getDate(),
  ).padStart(2, '0')}`;
  const dow = getDayOfWeek(iso);
  // Salão funciona de Terça (2) a Sábado (6). Se abrir no Domingo (0) ou Segunda (1), inicia na próxima Terça.
  if (dow === 0) return addDaysISO(iso, 2);
  if (dow === 1) return addDaysISO(iso, 1);
  return iso;
}

